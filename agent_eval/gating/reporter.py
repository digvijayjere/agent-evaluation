"""Automated report generator for Release Gating (Markdown and JSON).

Produces clean, human-readable Markdown summaries for GitHub PR comments / GitLab MRs,
and structured JSON artifacts for downstream CI/CD deployment pipelines.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Union

from agent_eval.gating.comparator import GateStatus
from agent_eval.gating.evaluator import GateEvaluationResult


def generate_markdown_report(result: GateEvaluationResult) -> str:
    """Render a GitHub-flavored Markdown report detailing the release gating decision."""
    status_icon = "PASS" if result.status == GateStatus.PASS else ("WARN" if result.status == GateStatus.WARN else "FAIL")
    status_emoji = "[APPROVED]" if result.gate_passed else "[BLOCKED]"

    lines = [
        "# Enterprise Agent Evaluation & Release Gate Report",
        "",
        f"**Decision:** {status_emoji} **`{result.status.value}`** (Exit Code: `{result.exit_code}`)",
        f"**Summary:** {result.summary_text}",
        "",
        "---",
        "",
        "## Metric Performance & Baseline Comparison",
        "",
    ]

    if result.comparison:
        lines.extend([
            "| Metric | Baseline | Candidate | Delta | Status | Threshold |",
            "| :--- | :---: | :---: | :---: | :---: | :--- |",
        ])

        for key, delta in result.comparison.metric_deltas.items():
            badge = f"**`{delta.status.value}`**"
            if delta.status == GateStatus.FAIL:
                badge = "🔴 **FAIL**"
            elif delta.status == GateStatus.WARN:
                badge = "🟡 **WARN**"
            else:
                badge = "🟢 **PASS**"

            delta_str = f"{delta.relative_percent_delta:+.2f}%" if "Latency" not in delta.metric_name else f"{delta.relative_percent_delta:+.1f}%"
            lines.append(
                f"| **{delta.metric_name}** | {delta.baseline_value:.4f} | {delta.candidate_value:.4f} | {delta_str} | {badge} | {delta.threshold_applied} |"
            )
        lines.append("")
    else:
        # Standalone summary
        cs = result.candidate_summary
        if cs:
            lines.extend([
                "| Metric | Candidate Value |",
                "| :--- | :---: |",
                f"| **Total Cases** | {cs.total_cases} |",
                f"| **Passed Cases** | {cs.passed_cases} |",
                f"| **Failed Cases** | {cs.failed_cases} |",
                f"| **F1 Score** | {cs.f1_score:.4f} |",
                f"| **Precision** | {cs.precision:.4f} |",
                f"| **Recall** | {cs.recall:.4f} |",
                f"| **Exact Match** | {cs.exact_match:.4f} |",
                f"| **Faithfulness Avg** | {cs.faithfulness_avg:.2f} / 5.00 |",
                f"| **Relevance Avg** | {cs.relevance_avg:.2f} / 5.00 |",
                f"| **Constraint Adherence Avg** | {cs.constraint_adherence_avg:.2f} / 5.00 |",
                f"| **Adversarial Refusal Rate** | {cs.adversarial_refusal_rate * 100:.1f}% |",
                f"| **Latency p95** | {cs.latency_p95:.2f} ms |",
                "",
            ])
        else:
            lines.extend([
                "| Metric | Candidate Score | Status |",
                "| :--- | :---: | :---: |",
                "| Total Cases | N/A | Completed |",
                "",
            ])

    if result.violations:
        lines.extend([
            "## Gating Violations Detected",
            "",
        ])
        for v in result.violations:
            lines.append(f"- ❌ {v}")
        lines.append("")

    lines.extend([
        "---",
        "*Automated report generated by `Enterprise-AgentEval-Hub` release gating pipeline.*",
    ])

    return "\n".join(lines)


def generate_json_report(
    result: GateEvaluationResult,
    output_path: Union[str, Path],
) -> None:
    """Export complete GateEvaluationResult to a JSON file."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(result.model_dump_json(indent=2), encoding="utf-8")
